def _bueno(id_, metodo, nombre, A, sol, variables, unidad, contexto, interpretacion):
    b=[sum(v*x for v,x in zip(fila,sol)) for fila in A]
    return dict(id=id_,metodo=metodo,nombre=nombre,A=A,b=b,esperado='resuelto',
        solucion_esperada=sol,variables=variables,unidad=unidad,
        contexto=contexto,interpretacion=interpretacion)

